// Builds tools/tg-bot/content.js for the Telegram bot from the app's own data:
// words of the day and quiz questions from dict/nl.json (+ recorded audio from audio/nl/texts.tsv),
// tips and app promos from tools/tg-bot/posts.json. Run after changing any of them:
//   node tools/tg-bot/build-content.mjs
import {readFileSync, writeFileSync} from "node:fs";

const root = new URL("../../", import.meta.url);
const read = p => readFileSync(new URL(p, root), "utf8");
const dict = JSON.parse(read("dict/nl.json"));
const posts = JSON.parse(read("tools/tg-bot/posts.json"));
const audio = new Map(read("audio/nl/texts.tsv").trim().split("\n").map(l => l.split("\t").reverse()));
const recorded = new Set(JSON.parse(read("audio/nl/manifest.json")));
const hashOf = text => (h => h && recorded.has(h) ? h : "")(audio.get(text));

// Seeded shuffle: the order looks random but stays the same between builds.
function shuffle(list, seed) {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    const j = Math.floor(seed / 2147483648 * (i + 1)); // high bits: the low bits of this generator repeat
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
const label = e => (e.g ? e.g + " " : "") + e.w;
const short = s => s.length <= 40 && !/[()]/.test(s);

// Word of the day: course level 1 words that have an example sentence.
const words = shuffle(dict.filter(e => e.l === 1 && e.x && e.xu && e.p !== "num"), 7).map(e => ({
  w: label(e), uk: e.uk, pl: e.pl || "", x: e.x, xu: e.xu, a: hashOf(label(e)) || hashOf(e.w), xa: hashOf(e.x)
}));

// Quiz: "what does X mean?" with three wrong answers of the same part of speech.
const pool = dict.filter(e => e.l === 1 && short(e.uk) && !["num", "phr"].includes(e.p));
const quiz = shuffle(pool, 11).map((e, n) => {
  const same = pool.filter(o => o.p === e.p && o.uk !== e.uk && o.w !== e.w);
  const wrong = shuffle(same, n + 3).filter((o, i, a) => a.findIndex(b => b.uk === o.uk) === i).slice(0, 3).map(o => o.uk);
  const options = shuffle([e.uk, ...wrong], n + 5);
  return {q: `Що означає «${label(e)}»?`, o: options, c: options.indexOf(e.uk), x: e.x ? `${e.x} — ${e.xu}` : ""};
}).filter(q => q.o.length === 4);

const out = {words, quiz, welcome: posts.welcome, tips: posts.tips, facts: posts.facts, promos: posts.promos};
writeFileSync(new URL("tools/tg-bot/content.js", root),
  "// Generated by tools/tg-bot/build-content.mjs: do not edit by hand.\nexport default " + JSON.stringify(out) + ";\n");
console.log(`words ${words.length} (${words.filter(w => w.a).length} with audio), quiz ${quiz.length}, tips ${posts.tips.length}, facts ${posts.facts.length}, promos ${posts.promos.length}`);
